"""Radio Airplay Reconciler - Streamlit dashboard.

Run with:  streamlit run app.py
"""
import sys
from pathlib import Path

import altair as alt
import pandas as pd
import streamlit as st

sys.path.insert(0, str(Path(__file__).resolve().parent / "src"))
from checks import CANCON_MIN, check_cancon, check_log_gaps, check_missing_isrc, check_unmatched  # noqa: E402
from pipeline import RAW, add_clean_columns, load_all, match_catalog  # noqa: E402

st.set_page_config(page_title="Radio Airplay Reconciler", page_icon="📻", layout="wide")


@st.cache_data
def get_data():
    df = add_clean_columns(load_all())
    catalog = add_clean_columns(pd.read_csv(RAW / "catalog.csv"))
    result = match_catalog(df, catalog)
    report = pd.DataFrame(
        check_cancon(result) + check_log_gaps(result) + check_unmatched(result) + check_missing_isrc(result)
    ).sort_values(["station", "check"]).reset_index(drop=True)
    return result, report


result, report = get_data()

# ---------------- Sidebar ----------------
st.sidebar.header("Filters")
stations = sorted(result["station"].unique())
picked = st.sidebar.multiselect("Stations", stations, default=stations)
st.sidebar.caption(
    f"Log week: {result['played_at'].min():%b %d} - {result['played_at'].max():%b %d, %Y}\n\n"
    "Synthetic data generated by `src/generate_data.py`."
)
if not picked:
    st.warning("Pick at least one station.")
    st.stop()

data = result[result["station"].isin(picked)]
rep = report[report["station"].isin(picked)]
songs = data[data["item_type"] == "song"].copy()
songs["cancon"] = songs["is_cancon"].eq(True)

# ---------------- Header + KPIs ----------------
st.title("📻 Radio Airplay Reconciler")
st.caption("As-played logs from three stations, cleaned, matched to the label catalog, and checked for CRTC CanCon compliance.")

c1, c2, c3, c4 = st.columns(4)
c1.metric("Items logged", f"{len(data):,}")
c2.metric("Song plays", f"{len(songs):,}")
c3.metric("Matched to catalog", f"{(songs['match_method'] != 'unmatched').mean():.1%}")
fails = (rep["status"] == "FAIL").sum()
c4.metric("Failed checks", int(fails))

# ---------------- Compliance report ----------------
st.subheader("Compliance report")
STATUS_COLOURS = {"PASS": "background-color: #2e7d32; color: white; font-weight: bold",
                  "FAIL": "background-color: #c62828; color: white; font-weight: bold",
                  "WARN": "background-color: #f9a825; color: black; font-weight: bold"}
st.dataframe(
    rep.style.map(lambda v: STATUS_COLOURS.get(v, ""), subset=["status"]),
    hide_index=True, width="stretch",
    height=(len(rep) + 1) * 35 + 3,  # show every row, no inner scrolling
)

# ---------------- CanCon charts ----------------
left, right = st.columns(2)

with left:
    st.subheader("CanCon share by station")
    by_station = songs.groupby("station")["cancon"].mean().reset_index(name="share")
    bars = alt.Chart(by_station).mark_bar().encode(
        x=alt.X("station:N", title=None),
        y=alt.Y("share:Q", title="Canadian share of songs", axis=alt.Axis(format="%"), scale=alt.Scale(domain=[0, 0.5])),
        color=alt.condition(alt.datum.share >= CANCON_MIN, alt.value("#2e7d32"), alt.value("#c62828")),
        tooltip=["station", alt.Tooltip("share:Q", format=".1%")],
    )
    rule = alt.Chart(pd.DataFrame({"y": [CANCON_MIN]})).mark_rule(strokeDash=[6, 4]).encode(y="y:Q")
    st.altair_chart(bars + rule, width="stretch")
    st.caption("Dashed line = 35% CRTC minimum. Unmatched songs count as non-Canadian.")

with right:
    st.subheader("CanCon share by day")
    songs["day"] = songs["played_at"].dt.normalize()
    by_day = songs.groupby(["day", "station"])["cancon"].mean().reset_index(name="share")
    lines = alt.Chart(by_day).mark_line(point=True).encode(
        x=alt.X("day:T", title=None, axis=alt.Axis(format="%a %d")),
        y=alt.Y("share:Q", title="Canadian share of songs", axis=alt.Axis(format="%"), scale=alt.Scale(domain=[0, 0.5])),
        color="station:N",
        tooltip=["station", alt.Tooltip("day:T", format="%a %b %d"), alt.Tooltip("share:Q", format=".1%")],
    )
    st.altair_chart(lines + rule, width="stretch")

# ---------------- Matching detail ----------------
st.subheader("How songs were matched")
method = songs.groupby(["station", "match_method"]).size().reset_index(name="plays")
st.altair_chart(
    alt.Chart(method).mark_bar().encode(
        x=alt.X("plays:Q", stack="normalize", title="Share of song plays", axis=alt.Axis(format="%")),
        y=alt.Y("station:N", title=None),
        color=alt.Color("match_method:N", title="Matched by",
                        scale=alt.Scale(domain=["isrc", "name", "unmatched"], range=["#1565c0", "#90caf9", "#c62828"])),
        tooltip=["station", "match_method", "plays"],
    ).properties(height=160),
    width="stretch",
)
st.caption("ISRC is an exact ID. Stations that don't log ISRCs fall back to cleaned title + artist.")

# ---------------- Unmatched songs ----------------
st.subheader("Songs not in the catalog")
unmatched = (
    songs[songs["match_method"] == "unmatched"]
    .assign(title=lambda d: d["title_clean"].str.title(), artist=lambda d: d["artist_clean"].str.title())
    .groupby(["title", "artist", "station"]).size().unstack(fill_value=0)
)
if unmatched.empty:
    st.success("Every song play matched a catalog track.")
else:
    unmatched["total"] = unmatched.sum(axis=1)
    st.dataframe(unmatched.sort_values("total", ascending=False), width="stretch")

# ---------------- Raw data ----------------
with st.expander("Browse the cleaned play log"):
    cols = ["station", "played_at", "item_type", "title", "artist", "isrc", "match_method", "is_cancon", "label"]
    st.dataframe(data[cols], hide_index=True, width="stretch")
    st.download_button("Download as CSV", data[cols].to_csv(index=False), "airplay_matched.csv", "text/csv")
